const norm = rows => rows.map(r => (r + '............').slice(0, 12)).slice(0, 12);
function svg({ shape, pal, name }) {
  const rows = norm(S[shape]);
  if (!S[shape]) throw new Error('missing shape ' + shape);
  const runs = {};
  rows.forEach((row, y) => {
    let x = 0;
    while (x < 12) {
      const ch = row[x];
      if (ch === '.') { x++; continue; }
      let w = 1; while (x + w < 12 && row[x + w] === ch) w++;
      if (!pal[ch]) throw new Error(`icon ${name}: no color for "${ch}"`);
      (runs[pal[ch]] = runs[pal[ch]] || []).push(`M${x} ${y}h${w}v1h-${w}z`);
      x += w;
    }
  });
  const paths = Object.entries(runs).map(([c, d]) => `<path fill='${c}' d='${d.join('')}'/>`).join('');
  return `<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 12 12' shape-rendering='crispEdges'>${paths}</svg>`;
}
const enc = s => s.replace(/#/g, '%23').replace(/</g, '%3C').replace(/>/g, '%3E');

